// WAP to Use All Relational Operators by Differnt Comparisons

let a = 10;
let b = 20;
let c = "30";

console.log("Value of a =", a);
console.log("Value of b =", b);
console.log("Value of c =", c);

console.log("All Relational Operators in JavaScript:");

// Greater Than Comparison //
console.log("a > b =", a > b);

// Less Than Comparison //
console.log("a < b =", a < b);

// Greater Than or Equal To Comparison //
console.log("a >= b =", a >= b);

// Less Than or Equal To Comparison //
console.log("a <= b =", a <= b);

// Equal To (Value) Comparison //
console.log("a == c =", a == c);

// Strict Equal (Value + Data Type) Comparison //
console.log("a === c =", a === c);

// Not Equal (Value) Comparison //
console.log("a != b =", a != b);

// Strict Not Equal (Value + Data Type) Comparison //
console.log("a !== c =", a !== c);
