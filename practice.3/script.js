// Declare Celsius temperature
let celsius = 150;

// Convert Celsius to Fahrenheit
let fahrenheit = (celsius * 9 / 5) + 32;

// Display Output
document.writeln("<h2>Temperature Converter</h2>");
document.writeln("Temperature in Celsius = " + celsius + "°C <br>");
document.writeln("Temperature in Fahrenheit = " + fahrenheit + "°F");
